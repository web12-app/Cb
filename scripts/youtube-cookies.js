#!/usr/bin/env node
"use strict";

// Creates a Netscape-format cookies.txt for YouTube so yt-dlp can get past the
// "Sign in to confirm you're not a bot" / HTTP 403 checks.
//
//   npm run cookies              # writes ./cookies.txt
//   node scripts/youtube-cookies.js /path/to/cookies.txt
//
// It loads https://www.youtube.com in a headless browser and exports the
// cookies it receives. Install a browser driver first:
//   npm i -D puppeteer
// or skip cookies.txt entirely and use a profile you already have:
//   YTDLP_COOKIES_FROM_BROWSER=chrome node server.js

const fs = require("node:fs");
const path = require("node:path");

const OUT = process.argv[2] || process.env.COOKIES_FILE || path.join(process.cwd(), "cookies.txt");
const START = process.env.COOKIES_START_URL || "https://www.youtube.com/";

function toNetscape(cookies) {
  const lines = [
    "# Netscape HTTP Cookie File",
    "# Generated by scripts/youtube-cookies.js",
    ""
  ];

  for (const c of cookies) {
    const domain = c.domain || ".youtube.com";
    const includeSub = domain.startsWith(".") ? "TRUE" : "FALSE";
    const expires =
      c.expires && c.expires > 0
        ? Math.floor(c.expires)
        : Math.floor(Date.now() / 1000) + 60 * 60 * 24 * 365;

    lines.push(
      [domain, includeSub, c.path || "/", c.secure ? "TRUE" : "FALSE", expires, c.name, c.value].join("\t")
    );
  }

  return lines.join("\n") + "\n";
}

async function loadWithPuppeteer() {
  const puppeteer = require("puppeteer");
  const browser = await puppeteer.launch({
    headless: true,
    args: ["--no-sandbox", "--disable-setuid-sandbox", "--disable-dev-shm-usage"]
  });

  try {
    const page = await browser.newPage();
    await page.goto(START, { waitUntil: "domcontentloaded", timeout: 60000 });

    // Best-effort: dismiss a consent dialog if one shows up.
    await page
      .evaluate(() => {
        const button = [...document.querySelectorAll("button")].find((b) =>
          /accept all|i agree|accept/i.test(b.textContent || "")
        );
        if (button) button.click();
      })
      .catch(() => {});

    await new Promise((resolve) => setTimeout(resolve, 4000));
    return await browser.cookies();
  } finally {
    await browser.close();
  }
}

async function main() {
  let cookies;

  try {
    cookies = await loadWithPuppeteer();
  } catch (error) {
    console.error("Could not load youtube.com in a headless browser:", error.message);
    console.error("");
    console.error("Install a driver:");
    console.error("  npm i -D puppeteer");
    console.error("");
    console.error("Or use a browser profile you already have (no cookies.txt needed):");
    console.error("  YTDLP_COOKIES_FROM_BROWSER=chrome node server.js");
    console.error("");
    console.error("Or export cookies with a \"Get cookies.txt\" browser extension and save them as cookies.txt.");
    process.exit(1);
  }

  const youtube = cookies.filter((c) => /(^|\.)youtube\.com$|(^|\.)google\.com$/.test(c.domain || ""));

  if (!youtube.length) {
    console.error("No YouTube cookies were captured. Open youtube.com in a browser and try again.");
    process.exit(1);
  }

  fs.writeFileSync(OUT, toNetscape(youtube));
  console.log(`Wrote ${youtube.length} cookies to ${OUT}`);
  console.log(`Start the server with:  YTDLP_COOKIES=${OUT} node server.js`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
